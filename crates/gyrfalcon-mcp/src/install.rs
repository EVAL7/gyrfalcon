/// Что установщик сделал (или сделал бы в режиме плана).
#[derive(Debug)]
pub struct Действие {
    pub харнес: &'static str,
    pub что: &'static str,
    pub куда: PathBuf,
    pub итог: String,
}

/// Разложить скилл (и показать, куда пошла бы запись MCP).
///
/// `plan = true` — ничего не пишет, только перечисляет. Режим существует
/// потому, что установщик трогает чужие конфиги: показать намерение до
/// записи дешевле, чем разбирать последствия после.
pub fn install(harnesses: &[Harness], plan: bool, force: bool) -> Vec<Действие> {
    let mut out = Vec::new();
    for &h in harnesses {
        let Some(p) = places(h) else {
            out.push(Действие {
                харнес: h.name(),
                что: "skill",
                куда: PathBuf::new(),
                итог: "не найден домашний каталог (USERPROFILE/HOME)".into(),
            });
            continue;
        };

        let итог = if plan {
            "план: будет записан".to_string()
        } else {
            match записать(&p.skill, &skill_with_stamp(), force) {
                Ok(s) => s,
                Err(e) => format!("ОШИБКА: {e}"),
            }
        };
        out.push(Действие {
            харнес: h.name(),
            что: "skill",
            куда: p.skill,
            итог,
        });

        // Три роли: различаются правом на утверждение, привязаны к профилям
        // сервера. Ставятся файлами, потому что харнес читает их сам.
        for t in Tier::ALL {
            let путь = p.agents.join(format!("{}.{}", t.agent_name(), p.agent_ext));
            let итог = if plan {
                "план: будет записан".to_string()
            } else {
                let toml = p.agent_ext == "toml";
                match записать(&путь, &с_отметкой(&роль(h, *t), toml), force)
                {
                    Ok(s) => s,
                    Err(e) => format!("ОШИБКА: {e}"),
                }
            };
            out.push(Действие {
                харнес: h.name(),
                что: "agent",
                куда: путь,
                итог,
            });
        }

        // Хуки-подсказки. НИКОГДА не блокируют вызов (см. модуль hooks):
        // молчаливый exit 0 при любой неудаче.
        let бинарь = std::env::current_exe()
            .map(|p| p.display().to_string())
            .unwrap_or_else(|_| "gyrfalcon".into());
        for e in crate::hooks::Event::ALL {
            let путь = crate::hooks::script_path(&p.hooks, *e);
            let тело = if cfg!(windows) {
                crate::hooks::script_cmd(&бинарь, *e)
            } else {
                crate::hooks::script_sh(&бинарь, *e)
            };
            let итог = if plan {
                "план: будет записан".to_string()
            } else {
                match записать(&путь, &тело, force) {
                    Ok(s) => s,
                    Err(e) => format!("ОШИБКА: {e}"),
                }
            };
            out.push(Действие {
                харнес: h.name(),
                что: "hook",
                куда: путь,
                итог,
            });
        }

        // Запись MCP-сервера в чужой конфиг не делается молча: у каждого
        // харнеса свой формат (JSON у одних, TOML у Codex), и порча живого
        // конфига дороже, чем строка, которую человек впишет сам. Регистрация
        // самих хуков в конфиге — там же: она правит тот же файл.
        out.push(Действие {
            харнес: h.name(),
            что: "mcp",
            куда: p.mcp_config,
            итог: "правится вручную — см. напечатанный фрагмент".into(),
        });
    }
    out
}

/// Записать файл, не затирая правленный человеком.
///
/// Приём взят у образца: чужую правку молча терять нельзя, перезапись —
/// только по `--force`. С 0.1.16 «чужая правка» определяется отметкой, а не
/// любым отличием: файл прежней версии, которого никто не трогал,
/// обновляется сам (см. [`ОТМЕТКА`]).
fn записать(куда: &Path, что: &str, force: bool) -> std::io::Result<String> {
    let mut итог_замены = None;
    if куда.exists() && !force {
        let текущий = std::fs::read_to_string(куда).unwrap_or_default();
        // Тот же текст в CRLF (выгрузка git на Windows) — тот же файл.
        if к_lf(&текущий) == к_lf(что) {
            return Ok("уже актуален".into());
        }
        match состояние(&текущий) {
            Состояние::Нетронут { версия } => {
                итог_замены = Some(format!("обновлён с {версия} до {VERSION}"));
            }
            Состояние::Правлен { версия } => {
                return Ok(format!(
                    "версия {версия} правлена вручную — перезаписать: --force"
                ));
            }
            Состояние::БезОтметки => {
                return Ok(
                    "есть без отметки версии (поставлен до 0.1.16 или правлен) — \
                     сверьте и перезапишите: --force"
                        .into(),
                );
            }
        }
    }
    if let Some(dir) = куда.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(куда, что)?;
    Ok(итог_замены.unwrap_or_else(|| format!("записан, {} байт", что.len())))
}

/// Установленные файлы gyrfalcon, которые отстали от бинаря, — для ответа
/// `list_projects`. Скилл и роли ищутся во всех известных харнесах; файла
/// нет — молчим (харнесом могут не пользоваться). Предупреждение едет в
/// ответ сервера, а не в документацию: документацию про обновление скилла
/// человек не перечитывает, а ответ агент видит каждый раз.
pub fn отставшие_установки() -> Vec<String> {
    let mut out = Vec::new();
    for &h in Harness::ALL {
        let Some(p) = places(h) else { continue };
        let toml = p.agent_ext == "toml";
        let роли = Tier::ALL.iter().map(|t| {
            (
                p.agents.join(format!("{}.{}", t.agent_name(), p.agent_ext)),
                роль(h, *t),
            )
        });
        for (путь, ожидаемое) in std::iter::once((p.skill.clone(), SKILL.to_string())).chain(роли)
        {
            let Ok(текст) = std::fs::read_to_string(&путь) else {
                continue;
            };
            if let Some(причина) = отставание(&текст, &ожидаемое, toml)
            {
                out.push(format!(
                    "{} {}: {причина} — выполните `gyrfalcon install`",
                    h.name(),
                    путь.display()
                ));
            }
        }
    }
    out
}

/// Тело установленного файла — без строки-отметки и того, что после неё,
/// с переводами строк в LF.
fn тело_без_отметки(текст: &str) -> String {
    let т = к_lf(текст);
    let т = т.as_ref();
    let тело = match т.rfind(ОТМЕТКА) {
        Some(i) => &т[..т[..i].rfind('\n').map_or(0, |j| j + 1)],
        None => т,
    };
    тело.trim_end_matches('\n').to_string()
}

/// Отстал ли установленный файл от того, что положил бы этот бинарь.
/// `None` — не отстал.
///
/// Сравнивается ТЕКСТ, а не номер версии. В 0.1.16 сравнивался номер — и
/// после каждого выпуска копии с неизменным текстом назывались бы
/// устаревшими: шум, который приучает не читать предупреждение.
/// Файл, правленный вручную при отметке текущей версии, — сознательная
/// правка, а не отставание: о нём молчим.
fn отставание(текст: &str, ожидаемое: &str, toml: bool) -> Option<String> {
    let свежий = с_отметкой(ожидаемое, toml);
    if тело_без_отметки(текст) == тело_без_отметки(&свежий) {
        return None;
    }
    match состояние(текст) {
        Состояние::Правлен { версия } if версия == VERSION => None,
        Состояние::БезОтметки => Some(format!(
            "поставлен до 0.1.16 (без отметки версии), текст отличается от сервера {VERSION}"
        )),
        Состояние::Нетронут { версия } | Состояние::Правлен { версия } => {
            Some(format!(
                "текст версии {версия} отличается от сервера {VERSION}"
            ))
        }
    }
}

/// Фрагмент конфигурации MCP для харнеса — печатается, а не вписывается.
///
/// **Серверов объявляется три, а не один.** Профиль задаётся при запуске
/// (`--profile`), поэтому одна запись означала бы один набор инструментов на
/// все роли: либо `sql` есть у разведчика, либо его нет у аудитора. Отдельная
/// запись на профиль — единственный способ сделать урезание механическим,
/// а не обещанием в тексте роли.
pub fn фрагмент(h: Harness, db: &str) -> String {
    let бинарь = std::env::current_exe()
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| "gyrfalcon".into())
        .replace('\\', "/");
    let db = db.replace('\\', "/");

    match h {
        Harness::Codex => Tier::ALL
            .iter()
            .map(|t| {
                format!(
                    "[mcp_servers.{}]\ncommand = \"{}\"\nargs = [\"serve\", \"--db\", \"{}\", \
                     \"--profile\", \"{}\"]\n\n",
                    имя_сервера(*t),
                    бинарь,
                    db,
                    t.profile()
                )
            })
            .collect(),
        _ => {
            let записи: Vec<String> = Tier::ALL
                .iter()
                .map(|t| {
                    format!(
                        "    \"{}\": {{\n      \"command\": \"{}\",\n      \"args\": \
                         [\"serve\", \"--db\", \"{}\", \"--profile\", \"{}\"]\n    }}",
                        имя_сервера(*t),
                        бинарь,
                        db,
                        t.profile()
                    )
                })
                .collect();
            format!(
                "{{\n  \"mcpServers\": {{\n{}\n  }}\n}}\n",
                записи.join(",\n")
            )
        }
    }
}

/// Фрагмент регистрации хуков — тоже печатается.
///
/// Хуки цепляются к событиям харнеса, и запись эту делает человек: чужой
/// конфиг может содержать его собственные хуки на те же события, а
/// автоматическая правка их порядка — не то, что стоит делать молча.
pub fn фрагмент_хуков(h: Harness) -> String {
    let Some(p) = places(h) else {
        return String::new();
    };
    let mut out = String::from("{\n  \"hooks\": {\n");
    let строки: Vec<String> = crate::hooks::Event::ALL
        .iter()
        .map(|e| {
            let путь = crate::hooks::script_path(&p.hooks, *e)
                .display()
                .to_string()
                .replace('\\', "/");
            match e.matcher() {
                Some(m) => format!(
                    "    \"{}\": [{{\"matcher\": \"{}\", \"hooks\": [{{\"type\": \"command\", \
                     \"command\": \"{}\"}}]}}]",
                    e.hook_event(),
                    m,
                    путь
                ),
                None => format!(
                    "    \"{}\": [{{\"hooks\": [{{\"type\": \"command\", \"command\": \
                     \"{}\"}}]}}]",
                    e.hook_event(),
                    путь
                ),
            }
        })
        .collect();
    out.push_str(&строки.join(",\n"));
    out.push_str("\n  }\n}\n");
    out
}

