pub const SKILL: &str = include_str!("../../../skills/gyrfalcon/SKILL.md");

/// Версия бинаря — она же версия текстов, которые он раскладывает.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Начало строки-отметки в установленном файле.
///
/// # Зачем отметка
///
/// Установщик не затирает правленный человеком файл — и до 0.1.16 поэтому
/// не мог обновить и НЕправленный: «старая версия от нас» и «правка
/// человека» на диске выглядели одинаково — просто другой текст. Итог —
/// скилл, застрявший на версии первой установки при сервере на десять
/// версий новее (13.10.2026: у владельца 0.1.5 при 0.1.14, без четырёх
/// инструментов).
///
/// Отметка несёт версию и хэш тела. Хэш сходится — файл никто не трогал,
/// его можно молча обновить; не сходится — правил человек, нужен `--force`.
const ОТМЕТКА: &str = "gyrfalcon-stamp";

/// Хэш тела — первые 16 знаков SHA-256: для «правили или нет» хватает.
///
/// Считается по тексту с переводами строк, приведёнными к LF: git с
/// `core.autocrlf=true` выгружает файл в CRLF, и это не правка человека.
/// В 0.1.16 хэш был чувствителен к CRLF, и после такой выгрузки `install`
/// считал нетронутый скилл правленным и переставал его обновлять.
fn хэш(тело: &str) -> String {
    use sha2::{Digest, Sha256};
    let lf = к_lf(тело);
    format!("{:x}", Sha256::digest(lf.as_bytes()))[..16].to_string()
}

/// Переводы строк — к LF. Одиночный `\r` в наших текстах не встречается.
fn к_lf(текст: &str) -> std::borrow::Cow<'_, str> {
    if текст.contains('\r') {
        std::borrow::Cow::Owned(текст.replace("\r\n", "\n"))
    } else {
        std::borrow::Cow::Borrowed(текст)
    }
}

/// Тело + строка-отметка. Markdown получает HTML-комментарий (не виден
/// в отрисовке), TOML — комментарий `#`.
pub fn с_отметкой(тело: &str, toml: bool) -> String {
    let т = тело.trim_end_matches('\n');
    let метка = format!("{ОТМЕТКА} version={VERSION} sha256={}", хэш(т));
    if toml {
        format!("{т}\n# {метка}\n")
    } else {
        format!("{т}\n<!-- {метка} -->\n")
    }
}

/// Что известно об установленном файле по его отметке.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Состояние {
    /// Отметки нет: поставлен до 0.1.16 или написан не нами.
    БезОтметки,
    /// Отметка есть, хэш тела сходится — файл не правили.
    Нетронут { версия: String },
    /// Отметка есть, тело правили после установки.
    Правлен { версия: String },
}

pub fn состояние(текст: &str) -> Состояние {
    // Отметка ищется в ЛЮБОЙ строке, а не только в последней: человек мог
    // дописать заметку ниже неё (живая проба 13.10.2026 — без этого файл
    // был защищён верно, но с ложным «без отметки»). Текст после отметки —
    // тоже правка. Разбор — по тексту в LF (см. `хэш`).
    let текст = к_lf(текст);
    let текст = текст.as_ref();
    let Some(начало) = текст.rfind(ОТМЕТКА) else {
        return Состояние::БезОтметки;
    };
    let начало_строки = текст[..начало].rfind('\n').map_or(0, |i| i + 1);
    let конец_строки = текст[начало..]
        .find('\n')
        .map_or(текст.len(), |i| начало + i);
    let строка = &текст[начало..конец_строки];
    let тело = текст[..начало_строки].trim_end_matches('\n');
    let хвост = текст[конец_строки..].trim();
    let поле = |ключ: &str| {
        строка
            .split_whitespace()
            .find_map(|p| p.strip_prefix(ключ))
            .unwrap_or("")
            .trim_end_matches("-->")
            .to_string()
    };
    let версия = поле("version=");
    if хвост.is_empty() && поле("sha256=") == хэш(тело) {
        Состояние::Нетронут { версия }
    } else {
        Состояние::Правлен { версия }
    }
}

