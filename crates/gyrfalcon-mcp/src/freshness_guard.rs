//! Сторож свежести индекса: следит за исходниками и помечает ответы отставшего индекса.
//!
//! # Почему подписка, а не обход (замер 29.08.2026)
//!
//! Первая редакция обходила дерево и держала итог в кэше на полминуты.
//! Замер её и похоронил:
//!
//! | корпус | файлов | обход | ответ инструмента |
//! |---|---|---|---|
//! | ДО | 22 829 | 1,76 с | 0,02 с |
//! | БП | 83 795 | 6,51 с | 0,06 с |
//! | ЕРП.УХ | 127 935 | **9,88 с** | **0,12 с** |
//!
//! Проверка выходила в 80 раз дороже ответа, который она сопровождает, —
//! и повторялась каждые полминуты. Сервер, чьё достоинство в миллисекундах
//! на запрос, платил бы за отметку свежести двадцатью минутами на часовой
//! сессии. (В комментарии тогда стояло «~1–2 с» — цифра, написанная на
//! глаз и не мерянная. Замер её опроверг.)
//!
//! Отсюда устройство:
//!
//! 1. **обход ровно один** — в фоновом потоке при старте, не задерживая
//!    ответы. Пока он идёт, сервер отвечает и честно говорит, что свежесть
//!    ещё проверяется;
//! 2. **дальше подписка** на события файловой системы (`notify`): правка
//!    видна мгновенно и не стоит ничего;
//! 3. **git HEAD** перечитывается при каждом обращении — это чтение одного
//!    маленького файла, доли миллисекунды, и оно ловит `checkout`, которого
//!    события не покажут как содержательную правку.
//!
//! # Почему события не заменяют первый обход
//!
//! Подписка говорит про то, что случилось ПОСЛЕ неё. Файл, изменённый
//! между сборкой индекса и запуском сервера, ей не виден вовсе — а это
//! самый обычный случай: собрали индекс вечером, правили утром, запустили
//! сервер днём. Обход отвечает на вопрос «что накопилось», подписка — «что
//! происходит сейчас»; ни один не заменяет другого.
//!
//! # Чего сторож НЕ делает
//!
//! Не пересобирает индекс. Отметка — это предупреждение, а решение
//! пересобирать принимает человек или отдельная команда: сервер, молча
//! запускающий десятиминутную сборку в ответ на вопрос агента, был бы
//! хуже отставшего.

use gyrfalcon_index::freshness::Freshness;
use notify::{RecursiveMode, Watcher};
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};

/// Общее состояние: пишет фоновый поток, читает поток ответов.
#[derive(Default)]
struct Состояние {
    /// Первый обход закончен.
    готово: AtomicBool,
    /// Файлов, изменённых ПОСЛЕ сборки индекса — по первому обходу.
    ///
    /// Отдельно от событийного счётчика, потому что уменьшать их можно
    /// по-разному. Обход считает расхождение с моментом сборки: среди этих
    /// файлов бывают метаданные, а по ним автодосборка отказывает целиком,
    /// и вычесть тут нечего — цифра честно стоит до полной пересборки.
    изменено: AtomicUsize,
    /// Файлов, изменённых при живом сервере — по событиям подписки.
    ///
    /// Их автодосборка догоняет и уменьшает счётчик на догнанное. Смешивать
    /// с обходом нельзя: раньше счётчик был один, и после успешной досборки
    /// отметка «индекс отстал» держалась вечно — вычиталось событийное,
    /// а стояло в нём и обходное. Поймано живой пробой 31.08.2026.
    изменено_событиями: AtomicUsize,
    /// Несколько путей — чтобы утверждение можно было проверить.
    примеры: Mutex<Vec<String>>,
    /// Сведения из самого индекса: когда собран, откуда, на каком коммите.
    основа: Mutex<Freshness>,
    /// ПОЛНЫЕ пути изменённого — для автодосборки (`autoupdate`).
    ///
    /// Отдельно от `примеры`, потому что отвечают на разные вопросы:
    /// примеры показывают человеку, что утверждение проверяемо, и потому
    /// их три; здесь нужен весь список, иначе догонять нечего.
    ///
    /// Копится только от СОБЫТИЙ. Первый обход сюда не пишет намеренно:
    /// он считает расхождение с моментом сборки индекса, и среди этих
    /// файлов запросто окажутся метаданные — а по ним инкремент отказывает
    /// целиком (см. `autoupdate`). Догонять на старте нечего: там нужна
    /// полная сборка, и о ней говорит отметка сторожа.
    очередь: Mutex<Vec<PathBuf>>,
}

/// Сколько путей называть поимённо.
const ПРИМЕРОВ: usize = 3;

/// Сторож. Живёт столько же, сколько сервер.
pub struct FreshnessGuard {
    состояние: Arc<Состояние>,
    /// Держим подписку живой: `notify` прекращает слежение, когда
    /// наблюдатель уничтожен. Поле не читается — в этом и смысл.
    ///
    /// В `Mutex` ради `Sync`: сторож проекта общий у всех потоков HTTP-сервера,
    /// а наблюдатель `notify` только `Send`. Замок никто не берёт — он нужен
    /// типу, а не исполнению.
    _наблюдатель: Option<Mutex<Box<dyn Watcher + Send>>>,
    /// Встала ли подписка на события.
    ///
    /// Наружу это выведено намеренно. Без неё сервер с УМЕРШЕЙ подпиской
    /// молчит ровно так же, как со свежим индексом: правки в середине
    /// сессии он уже не видит, а сказать об этом нечем. Молчание тогда
    /// значит два разных состояния сразу — тот самый дефект, ради которого
    /// затевалась веха 7, только этажом выше.
    подписка: bool,
    корень: Option<PathBuf>,
}

impl FreshnessGuard {
    /// Поднять сторожа для индекса: прочитать его метаданные, запустить
    /// обход фоном и подписаться на изменения.
    ///
    /// Не блокирует: на ЕРП.УХ обход длится десять секунд, и держать
    /// первый ответ агента всё это время значило бы вылечить одну болезнь
    /// другой.
    pub fn запустить(db: &Path) -> Self {
        let состояние = Arc::new(Состояние::default());

        let Ok(info) = gyrfalcon_index::build::info(db) else {
            // Индекс не читается — сторожить нечего. Отказ «индекс
            // недоступен» придёт от самого инструмента; две беды в одном
            // тексте читаются как одна.
            состояние.готово.store(true, Ordering::Release);
            return Self {
                состояние,
                _наблюдатель: None,
                подписка: false,
                корень: None,
            };
        };

        let корень = PathBuf::from(&info.source_path);
        let база = Freshness {
            built_at: info.built_at,
            built_commit: info.git_commit.clone(),
            ..Default::default()
        };
        *состояние.основа.lock().unwrap() = база;

        if info.source_path.is_empty() || !корень.is_dir() {
            let mut b = состояние.основа.lock().unwrap();
            b.unchecked = Some(if info.source_path.is_empty() {
                "индекс не помнит, из какого каталога собран".into()
            } else {
                format!("каталога {} нет на этой машине", info.source_path)
            });
            drop(b);
            состояние.готово.store(true, Ordering::Release);
            return Self {
                состояние,
                _наблюдатель: None,
                подписка: false,
                корень: None,
            };
        }

        // --- подписка ставится ДО обхода ---
        //
        // Порядок не случаен: событие, случившееся во время обхода, иначе
        // потерялось бы между «обход это место уже прошёл» и «подписки ещё
        // нет». Лишний повтор (файл посчитан и обходом, и событием) даёт
        // завышенный счётчик, а пропуск даёт молчащий индекс. Первое
        // безопаснее.
        let для_событий = Arc::clone(&состояние);
        let наблюдатель = поставить_подписку(&корень, для_событий);

        // --- обход фоном ---
        let для_обхода = Arc::clone(&состояние);
        let путь = корень.clone();
        let built_at = info.built_at;
        let коммит = info.git_commit.clone();
        std::thread::spawn(move || {
            let f = gyrfalcon_index::freshness::check(built_at, &путь.to_string_lossy(), &коммит);
            для_обхода.изменено.fetch_add(f.changed, Ordering::AcqRel);
            {
                let mut п = для_обхода.примеры.lock().unwrap();
                for e in f.examples {
                    if п.len() < ПРИМЕРОВ && !п.contains(&e) {
                        п.push(e);
                    }
                }
            }
            {
                let mut b = для_обхода.основа.lock().unwrap();
                b.current_commit = f.current_commit;
                b.unchecked = f.unchecked;
            }
            для_обхода.готово.store(true, Ordering::Release);
        });

        Self {
            состояние,
            подписка: наблюдатель.is_some(),
            _наблюдатель: наблюдатель.map(Mutex::new),
            корень: Some(корень),
        }
    }

    /// Что сказать агенту про свежесть — или `None`, если говорить нечего.
    fn отметка(&self) -> Option<String> {
        let основа = self.состояние.основа.lock().unwrap().clone();
        let готово = self.состояние.готово.load(Ordering::Acquire);

        // Коммит перечитывается каждый раз: `git checkout` не даёт событий,
        // которые мы могли бы отличить от обычной правки, а чтение
        // `.git/HEAD` стоит доли миллисекунды.
        let текущий = self
            .корень
            .as_ref()
            .and_then(|k| gyrfalcon_index::git::head(k))
            .unwrap_or_default();

        let изменено = self.состояние.изменено.load(Ordering::Acquire)
            + self.состояние.изменено_событиями.load(Ordering::Acquire);
        let примеры = self.состояние.примеры.lock().unwrap().clone();

        // Возраст считается ЗДЕСЬ, а не при старте: сессия живёт часами,
        // и «собран 2 ч назад», запомненное на старте, к вечеру врёт.
        let сейчас = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or(0);
        let возраст = сейчас.saturating_sub(основа.built_at);

        let f = Freshness {
            age_secs: возраст,
            stale: изменено > 0
                || (!основа.built_commit.is_empty()
                    && !текущий.is_empty()
                    && основа.built_commit != текущий),
            changed: изменено,
            examples: примеры,
            current_commit: текущий,
            ..основа
        };

        // Пока первый обход не кончился, «ничего не найдено» — это ещё не
        // «ничего нет». Молчать здесь значило бы выдать незнание за свежесть,
        // ровно тот дефект, ради которого веха 7 и затеяна.
        if !готово && !f.stale && f.unchecked.is_none() {
            return Some("свежесть индекса ещё проверяется (идёт первый обход)".into());
        }
        f.note()
    }

    /// Что накопилось для автодосборки. Список НЕ очищается.
    ///
    /// Разделение «посмотреть» и «признать обработанным» — правило образца
    /// (codebase-memory-mcp, баг #937): базовая линия сдвигается только
    /// после успешной пересборки. Иначе упавший или пропущенный инкремент
    /// стирает след правки, и расхождение становится невидимым — хуже,
    /// чем если бы автодосборки не было вовсе.
    pub fn очередь(&self) -> Vec<PathBuf> {
        self.состояние.очередь.lock().unwrap().clone()
    }

    /// Признать перечисленные файлы догнанными: убрать из очереди и
    /// уменьшить счётчик изменённых.
    ///
    /// Зовётся ТОЛЬКО после успешного инкремента. Убираются именно
    /// названные пути, а не весь список: пока шла досборка, могли прийти
    /// новые события, и стирать их значило бы терять правки ровно тем
    /// способом, от которого это правило и защищает.
    pub fn признать_догнанным(&self, файлы: &[PathBuf]) {
        let mut очередь = self.состояние.очередь.lock().unwrap();
        let было = очередь.len();
        очередь.retain(|p| !файлы.contains(p));
        let убрано = было.saturating_sub(очередь.len());
        drop(очередь);
        // Счётчик уменьшаем ровно на убранное: он же кормит отметку
        // «индекс отстал», и разъехавшись с очередью, она соврёт.
        self.состояние.изменено_событиями.fetch_sub(
            убрано.min(self.состояние.изменено_событиями.load(Ordering::Acquire)),
            Ordering::AcqRel,
        );
        if убрано > 0 {
            self.состояние.примеры.lock().unwrap().clear();
        }
    }

    /// Узнать о пересобранном индексе: заменить базу, обнулить накопленное.
    ///
    /// Зовётся после ПОЛНОЙ пересборки (git-синхронизация, метаданные):
    /// старые счётчики и очередь говорили про индекс, которого больше нет,
    /// и сторож продолжал бы кричать «отстал» об изменениях, которые
    /// пересборка только что поглотила. Новая база читается из самого
    /// индекса — как при старте.
    ///
    /// Событие, приехавшее от подписки ПОСЛЕ пересборки, но вызванное тем же
    /// pull'ом, посчитается заново: гонка между переименованием индекса и
    /// доставкой событий не разрешима здесь. Цена — одна лишняя отметка
    /// «отстал», снятая следующим успешным инкрементом.
    pub fn пересобран(&self, db: &Path) {
        let Ok(info) = gyrfalcon_index::build::info(db) else {
            return;
        };
        {
            let mut b = self.состояние.основа.lock().unwrap();
            b.built_at = info.built_at;
            b.built_commit = info.git_commit.clone();
            b.current_commit = info.git_commit.clone();
            b.unchecked = None;
        }
        self.состояние.изменено.store(0, Ordering::Release);
        self.состояние.изменено_событиями.store(0, Ordering::Release);
        self.состояние.очередь.lock().unwrap().clear();
        self.состояние.примеры.lock().unwrap().clear();
    }

    /// Состояние сторожа словами — для тех, кто спрашивает прямо.
    ///
    /// Отдельно от `отметка()`, потому что отвечает на ДРУГОЙ вопрос.
    /// `отметка` говорит «что-то не так» и молчит, когда всё хорошо;
    /// этот метод говорит, ЧТО именно проверено и чем — то есть отвечает
    /// на «а откуда я знаю, что всё нормально».
    pub fn состояние(&self) -> serde_json::Value {
        let основа = self.состояние.основа.lock().unwrap().clone();
        let готово = self.состояние.готово.load(Ordering::Acquire);
        let изменено = self.состояние.изменено.load(Ordering::Acquire)
            + self.состояние.изменено_событиями.load(Ordering::Acquire);

        let проверка = if основа.unchecked.is_some() {
            "не выполнена"
        } else if !готово {
            "идёт первый обход"
        } else if изменено > 0 {
            "индекс отстал"
        } else {
            "исходники сверены, расхождений нет"
        };

        // Раздельно, потому что действия разные: накопленное ДО старта
        // сервера автодосборка не трогает (там бывают метаданные — нужна
        // полная сборка), а появившееся ПРИ живом сервере она догоняет
        // сама. Одно число на двоих не давало понять, что именно осталось.
        let от_обхода = self.состояние.изменено.load(Ordering::Acquire);
        let от_событий = self.состояние.изменено_событиями.load(Ordering::Acquire);
        serde_json::json!({
            "checked": проверка,
            "changed_files": изменено,
            "changed_before_start": от_обхода,
            "changed_while_running": от_событий,
            "watching": self.подписка,
            "watch_note": if self.подписка {
                "правки в исходниках видны сразу: подписка на события файловой системы"
            } else {
                "ПОДПИСКА НЕ ВСТАЛА: расхождения, возникшие ПОСЛЕ старта сервера,                  замечены не будут. Перезапустите сервер или пересоберите индекс перед выводами"
            },
            "reason": основа.unchecked,
        })
    }

    /// Приписать отметку к ответу инструмента, если есть что сказать.
    ///
    /// Ответ, не являющийся объектом, оборачивается: терять данные ради
    /// приписки нельзя.
    pub fn пометить(&self, ответ: Value) -> Value {
        let Some(строка) = self.отметка() else {
            return ответ;
        };
        match ответ {
            Value::Object(mut m) => {
                m.insert("stale".into(), Value::String(строка));
                Value::Object(m)
            }
            другое => serde_json::json!({"result": другое, "stale": строка}),
        }
    }
}

/// Подписаться на изменения в каталоге выгрузки.
///
/// Ошибку подписки не считаем фатальной: без неё остаётся первый обход,
/// то есть сервер деградирует до состояния «знает, что было при старте»,
/// а не до молчания.
fn поставить_подписку(
    корень: &Path,
    состояние: Arc<Состояние>,
) -> Option<Box<dyn Watcher + Send>> {
    let корень_для_путей = корень.to_path_buf();
    let обработчик = move |событие: notify::Result<notify::Event>| {
        let Ok(e) = событие else { return };
        // Интересуют изменения содержимого и состава, а не чтение и не
        // смена прав: индекс читает ЧТО в файлах, а не как к ним обращались.
        if !matches!(
            e.kind,
            notify::EventKind::Create(_)
                | notify::EventKind::Modify(_)
                | notify::EventKind::Remove(_)
        ) {
            return;
        }
        for p in e.paths {
            let подходит = p
                .extension()
                .and_then(|x| x.to_str())
                .is_some_and(|x| x.eq_ignore_ascii_case("bsl") || x.eq_ignore_ascii_case("xml"));
            if !подходит {
                continue;
            }
            // Счётчик и очередь считают ОДНО И ТО ЖЕ — уникальные файлы.
            //
            // Раньше счётчик рос на каждое событие, а очередь хранила путь
            // один раз. Одно сохранение файла даёт несколько событий
            // (создание временного, переименование, запись), поэтому
            // `changed_files` показывал втрое больше правок, чем было, а
            // после успешной досборки не обнулялся вовсе: вычесть один
            // догнанный файл из счётчика, накрученного тремя событиями,
            // мало. Отметка «индекс отстал» держалась на догнанном индексе.
            // Поймано живой пробой 31.08.2026.
            let новый = {
                let mut очередь = состояние.очередь.lock().unwrap();
                if очередь.contains(&p) {
                    false
                } else {
                    очередь.push(p.clone());
                    true
                }
            };
            if !новый {
                continue;
            }
            состояние.изменено_событиями.fetch_add(1, Ordering::AcqRel);
            let mut примеры = состояние.примеры.lock().unwrap();
            if примеры.len() < ПРИМЕРОВ {
                let отн = gyrfalcon_index::extensions::rel_from(&корень_для_путей, &p);
                if !примеры.contains(&отн) {
                    примеры.push(отн);
                }
            }
        }
    };

    let mut w = notify::recommended_watcher(обработчик).ok()?;
    w.watch(корень, RecursiveMode::Recursive).ok()?;
    // Каталоги расширений лежат соседями `src` (Р-022) и в индексе наравне
    // с основной конфигурацией. Подписка на контейнер, а не на каждое
    // расширение: новое расширение, положенное туда, тоже должно быть видно.
    // Неудача здесь не роняет основную подписку — деградация, а не молчание.
    for d in gyrfalcon_index::extensions::extension_dirs(корень) {
        let _ = w.watch(&d, RecursiveMode::Recursive);
    }
    Some(Box::new(w))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    /// Сторож с заданным состоянием — без диска и без потоков.
    fn сторож(изменено: usize, готово: bool) -> FreshnessGuard {
        let общее = Arc::new(Состояние::default());
        общее.изменено.store(изменено, Ordering::Release);
        общее.готово.store(готово, Ordering::Release);
        // Задаётся ВРЕМЯ СБОРКИ, а не возраст: прежняя редакция теста
        // клала сюда `age_secs` готовым и потому проверяла саму себя —
        // возраст в отметке не считался вовсе и на живой пробе вышел
        // «собран 0 с назад» при семичасовом индексе.
        let два_часа_назад = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_secs()
            - 7200;
        *общее.основа.lock().unwrap() = Freshness {
            built_at: два_часа_назад,
            ..Default::default()
        };
        if изменено > 0 {
            общее
                .примеры
                .lock()
                .unwrap()
                .push("CommonModules/А/Ext/Module.bsl".into());
        }
        FreshnessGuard {
            состояние: общее,
            _наблюдатель: None,
            подписка: true,
            корень: None,
        }
    }

    #[test]
    fn отметка_приписывается_не_ломая_ответ() {
        let w = сторож(3, true);
        let ответ = json!({"columns": ["a"], "rows": [[1]], "count": 1});
        let итог = w.пометить(ответ);
        assert_eq!(итог["count"], 1, "данные ответа не тронуты");
        let s = итог["stale"].as_str().unwrap();
        assert!(s.contains("ОТСТАЛ"), "{s}");
        assert!(
            s.contains("Module.bsl"),
            "утверждение обязано быть проверяемым: {s}"
        );
    }

    #[test]
    fn возраст_считается_от_времени_сборки_а_не_берётся_готовым() {
        let w = сторож(1, true);
        let s = w.отметка().unwrap();
        assert!(s.contains("собран 2 ч назад"), "возраст не посчитан: {s}");
    }

    #[test]
    fn свежий_индекс_ничего_не_приписывает() {
        let w = сторож(0, true);
        let ответ = json!({"count": 0});
        assert_eq!(
            w.пометить(ответ.clone()),
            ответ,
            "свежий не платит ни знаком"
        );
    }

    #[test]
    fn пока_обход_идёт_молчания_нет() {
        // Ключевое свойство: незнание нельзя выдавать за свежесть.
        let w = сторож(0, false);
        let итог = w.пометить(json!({"count": 0}));
        let s = итог["stale"]
            .as_str()
            .expect("незнание обязано говорить о себе");
        assert!(s.contains("проверяется"), "{s}");
    }

    #[test]
    fn неотъектный_ответ_оборачивается_а_не_теряется() {
        let w = сторож(1, true);
        let итог = w.пометить(json!([1, 2, 3]));
        assert_eq!(итог["result"], json!([1, 2, 3]));
        assert!(итог["stale"].is_string());
    }

    #[test]
    fn недоступный_индекс_не_сторожится_и_не_врёт() {
        let w = FreshnessGuard::запустить(Path::new("Z:/нет/такого.db"));
        // Молчит: про свежесть того, чего не открыли, сказать нечего,
        // а отказ придёт от самого инструмента.
        assert_eq!(w.пометить(json!({"a": 1})), json!({"a": 1}));
    }

    #[test]
    fn событие_в_каталоге_поднимает_счётчик() {
        // Проверяем сам обработчик, а не notify: событие с путём .bsl
        // обязано увеличить счётчик и попасть в примеры.
        let общее = Arc::new(Состояние::default());
        общее.готово.store(true, Ordering::Release);
        let w = FreshnessGuard {
            состояние: Arc::clone(&общее),
            _наблюдатель: None,
            подписка: true,
            корень: None,
        };
        assert!(w.отметка().is_none(), "до события молчит");

        общее.изменено.fetch_add(1, Ordering::AcqRel);
        общее
            .примеры
            .lock()
            .unwrap()
            .push("Х/Ext/Module.bsl".into());
        let s = w.отметка().expect("после события обязана быть отметка");
        assert!(s.contains("файл изменён"), "склонение по числу: {s}");
    }
}
