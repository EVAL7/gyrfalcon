//! Автодосборка индекса: догонять исходники самому, а не только жаловаться.
//!
//! # Что было и чего не хватало
//!
//! Сторож свежести (`freshness_guard`) замечает отставание и помечает ответы,
//! но пересборку не запускает — по доводу «сервер, молча запускающий
//! десятиминутную сборку в ответ на вопрос агента, был бы хуже отставшего».
//! Довод верен для ПОЛНОЙ сборки и неверен для инкремента: он стоит
//! 6–10 с против 16–132 с, и на правку одного модуля тратится доля секунды.
//!
//! Отсюда разделение, которого раньше не было: отметка остаётся для того,
//! чего мы догнать не можем, а то, что можем, догоняется само.
//!
//! # Что взято у образца
//!
//! Устройство снято с `src/watcher/watcher.c` codebase-memory-mcp, читанного
//! по исходникам. Оттуда три решения, каждое со своим доводом:
//!
//! 1. **Выключено по умолчанию.** У образца `auto_index` умолчанием `false`
//!    (`cbm_config_get_bool(..., CBM_CONFIG_AUTO_INDEX, false)`) — вопреки
//!    их же README, где он подан как готовая возможность. Мы делаем так же:
//!    сборка трогает файл, которым сервер отвечает, и включать её за
//!    человека нельзя.
//! 2. **Адаптивный интервал** — у них 5 с база плюс 1 с на каждые 500 файлов,
//!    потолок 60 с. Довод: большой корпус и меняется реже, и проверяется
//!    дороже. Формулу берём их, числа тоже — они мерены на их корпусах,
//!    а наши того же порядка.
//! 3. **Базовая линия сдвигается ТОЛЬКО при успехе.** Их баг #937: пропущенная
//!    или упавшая пересборка обязана остаться в очереди, иначе отказ выглядит
//!    как «изменений не было». Это главное, что стоит перенять: без него
//!    автодосборка не улучшает положение, а прячет расхождение.
//!
//! # Чего у образца нет, а у нас обязано быть
//!
//! **Разделение BSL и XML.** Наш инкремент не принимает `.xml` и отвечает
//! отказом — правка метаданных задевает таблицы перекрёстными ссылками,
//! и выборочная чистка дала бы тихо расходящийся индекс. У образца такой
//! беды нет: там код и есть код.
//!
//! Значит слепое «изменилось — дособери» здесь не годится. Порядок такой:
//!
//! * изменились только `.bsl` → инкремент, тихо и быстро;
//! * среди изменений есть `.xml` → **инкремент не запускается вовсе**,
//!   отметка сторожа остаётся, и в ней сказано, что нужна полная сборка.
//!   Дособрать половину и промолчать про вторую — худший исход из трёх.
//!
//! # Чего этот модуль НЕ делает
//!
//! Не запускает полную сборку. Никогда и ни при каких настройках: она стоит
//! минуты, и решение о ней принимает человек. Автоматизируется ровно то,
//! что дёшево и обратимо.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::{Arc, Mutex};

/// Параметры опроса — числа образца (`POLL_BASE_MS`, `POLL_FILE_STEP`).
const БАЗА_МС: u64 = 5_000;
const ШАГ_ФАЙЛОВ: u64 = 500;
const ПОТОЛОК_МС: u64 = 60_000;

/// Интервал опроса по размеру корпуса: 5 с + 1 с на каждые 500 файлов, ≤ 60 с.
///
/// Формула образца целиком. Довод их же и он верен: корпус на сто тысяч
/// файлов и меняется реже, и стоит дороже в проверке, поэтому частить по
/// нему бессмысленно вдвойне.
pub fn интервал_мс(файлов: u64) -> u64 {
    (БАЗА_МС + (файлов / ШАГ_ФАЙЛОВ) * 1_000).min(ПОТОЛОК_МС)
}

/// Почему автодосборка не пошла. Каждая причина — отдельный случай,
/// потому что действия у них разные.
#[derive(Debug, Clone, PartialEq)]
pub enum Отказ {
    /// Изменений нет — обычный, самый частый исход.
    Нечего,
    /// Среди изменений есть метаданные: нужна полная сборка, её мы не делаем.
    ЕстьМетаданные { xml: usize, bsl: usize },
    /// Инкремент запускался и упал. Базовая линия НЕ сдвинута.
    Сбой(String),
}

/// Состояние автодосборки, разделяемое с сервером.
pub struct Автодосборка {
    включена: bool,
    db: PathBuf,
    корень: PathBuf,
    /// Идёт ли сейчас досборка: второй заход поверх первого не нужен.
    занято: Arc<AtomicBool>,
    /// Когда досбирали в последний раз (unix, с) — 0, если ни разу.
    последняя: Arc<AtomicU64>,
    /// Последний исход словами — для `list_projects`.
    последний_итог: Arc<Mutex<Option<String>>>,
}

impl Автодосборка {
    pub fn новая(db: &Path, корень: &Path, включена: bool) -> Self {
        Self {
            включена,
            db: db.to_path_buf(),
            корень: корень.to_path_buf(),
            занято: Arc::new(AtomicBool::new(false)),
            последняя: Arc::new(AtomicU64::new(0)),
            последний_итог: Arc::new(Mutex::new(None)),
        }
    }

    pub fn включена(&self) -> bool {
        self.включена
    }

    /// Разобрать список изменённых путей на то, что мы умеем догнать,
    /// и то, что требует полной сборки.
    ///
    /// Публична ради теста: правило «есть xml — не трогаем ничего»
    /// важнее прочего в этом модуле и обязано проверяться отдельно.
    pub fn разобрать(пути: &[PathBuf]) -> Result<Vec<PathBuf>, Отказ> {
        if пути.is_empty() {
            return Err(Отказ::Нечего);
        }
        let расширение = |p: &PathBuf| -> String {
            p.extension()
                .and_then(|x| x.to_str())
                .unwrap_or("")
                .to_ascii_lowercase()
        };
        let bsl: Vec<PathBuf> = пути
            .iter()
            .filter(|p| расширение(p) == "bsl")
            .cloned()
            .collect();
        let xml = пути.iter().filter(|p| расширение(p) == "xml").count();

        // Метаданные меняют перекрёстные ссылки — инкремент их не берёт,
        // и дособрать одни модули значило бы оставить индекс расходящимся
        // ровно в той части, о которой никто не спросит.
        if xml > 0 {
            return Err(Отказ::ЕстьМетаданные {
                xml,
                bsl: bsl.len(),
            });
        }
        if bsl.is_empty() {
            return Err(Отказ::Нечего);
        }
        Ok(bsl)
    }

    /// Догнать индекс по списку изменённых файлов.
    ///
    /// Возвращает `Ok` только когда инкремент прошёл — вызывающий сдвигает
    /// базовую линию ИМЕННО И ТОЛЬКО на `Ok`. Правило образца (#937):
    /// пропущенная правка обязана остаться в очереди, иначе отказ
    /// неотличим от отсутствия изменений.
    pub fn догнать(
        &self,
        изменённые: &[PathBuf],
    ) -> Result<gyrfalcon_index::incremental::IncrementReport, Отказ> {
        // Проверку «включена ли» делает вызывающий (`Server::догнать` — по
        // флагу --auto-update): git-синхронизация инкрементит и без него,
        // и второй страж внутри топил бы её отказом «Нечего».
        let файлы = Self::разобрать(изменённые)?;

        // Второй заход поверх идущего не нужен: он ждал бы блокировки
        // индекса и удвоил цену, ничего не добавив.
        if self.занято.swap(true, Ordering::AcqRel) {
            return Err(Отказ::Сбой("досборка уже идёт".into()));
        }
        let итог = gyrfalcon_index::incremental::update(&self.db, &self.корень, &файлы);
        self.занято.store(false, Ordering::Release);

        match итог {
            Ok(r) => {
                let сейчас = std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .map(|d| d.as_secs())
                    .unwrap_or(0);
                self.последняя.store(сейчас, Ordering::Release);
                let слова = format!(
                    "модулей {}, добавлено {}, удалено {}, за {} мс{}",
                    r.modules,
                    r.added,
                    r.removed,
                    r.elapsed_ms,
                    if r.stale_edges > 0 {
                        format!("; неразрешённых рёбер {}", r.stale_edges)
                    } else {
                        String::new()
                    }
                );
                *self.последний_итог.lock().unwrap() = Some(слова);
                Ok(r)
            }
            Err(e) => {
                let текст = e.to_string();
                *self.последний_итог.lock().unwrap() = Some(format!("ОШИБКА досборки: {текст}"));
                Err(Отказ::Сбой(текст))
            }
        }
    }

    /// Состояние словами — для `list_projects`.
    ///
    /// Выключенная досборка говорит об этом прямо: иначе «ничего не
    /// досбиралось» читалось бы как «нечего было дособирать».
    pub fn состояние(&self) -> serde_json::Value {
        if !self.включена {
            return serde_json::json!({
                "auto_update": "выключена",
                "note": "включить: --auto-update. Инкремент по .bsl; \
                         правка метаданных всё равно требует полной сборки"
            });
        }
        let последняя = self.последняя.load(Ordering::Acquire);
        serde_json::json!({
            "auto_update": "включена",
            "last_update": if последняя == 0 { serde_json::Value::Null }
                           else { serde_json::json!(последняя) },
            "last_result": *self.последний_итог.lock().unwrap(),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Формула интервала — числа образца.
    #[test]
    fn интервал_растёт_с_корпусом_и_упирается_в_потолок() {
        assert_eq!(интервал_мс(0), 5_000, "малый корпус — база");
        assert_eq!(интервал_мс(499), 5_000, "меньше шага — без надбавки");
        assert_eq!(интервал_мс(500), 6_000, "шаг = +1 с");
        assert_eq!(интервал_мс(12_257), 29_000, "ЗУП");
        // ЕРП.УХ: 127 935 файлов дали бы 260 с — упирается в потолок.
        assert_eq!(интервал_мс(127_935), 60_000, "потолок 60 с");
    }

    /// Главное правило модуля: одна изменённая метаданная отменяет
    /// досборку ЦЕЛИКОМ, а не только себя. Дособрать модули и промолчать
    /// про метаданные — оставить индекс расходящимся незаметно.
    #[test]
    fn метаданные_отменяют_досборку_целиком() {
        let пути = vec![
            PathBuf::from("CommonModules/М/Ext/Module.bsl"),
            PathBuf::from("Catalogs/Товары.xml"),
        ];
        match Автодосборка::разобрать(&пути) {
            Err(Отказ::ЕстьМетаданные { xml, bsl }) => {
                assert_eq!(xml, 1);
                assert_eq!(bsl, 1, "число bsl называется, чтобы было видно цену");
            }
            иное => panic!("ожидался отказ по метаданным, получено {иное:?}"),
        }
    }

    #[test]
    fn только_bsl_проходит() {
        let пути = vec![
            PathBuf::from("A/Ext/Module.bsl"),
            PathBuf::from("B/Ext/Module.BSL"),
        ];
        assert_eq!(Автодосборка::разобрать(&пути).unwrap().len(), 2);
    }

    #[test]
    fn пустой_список_это_нечего_а_не_ошибка() {
        assert_eq!(Автодосборка::разобрать(&[]), Err(Отказ::Нечего));
    }

    /// Выключённая досборка говорит о себе прямо, а не молчит.
    #[test]
    fn выключенная_называет_себя() {
        let досборка =
            Автодосборка::новая(Path::new("x.db"), Path::new("."), false);
        let итог = досборка.состояние();
        assert_eq!(итог["auto_update"], "выключена");
        assert!(итог["note"].as_str().unwrap().contains("--auto-update"));
    }
}
