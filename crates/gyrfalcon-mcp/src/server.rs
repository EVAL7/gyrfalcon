//! Цикл MCP-сервера: stdin → обработка → stdout.
//!
//! # Транспорт
//!
//! Одна строка = одно сообщение JSON-RPC. Это транспорт stdio, каким его
//! ожидают клиенты MCP.
//!
//! # Почему stdout свят
//!
//! В stdout идёт **только** JSON-RPC. Любая диагностика — в stderr. Одна
//! отладочная строка, напечатанная в stdout, делает сервер неработающим для
//! клиента, и выглядит это как «сервер не отвечает», а не как опечатка.
//!
//! # Потоки
//!
//! `handle` берёт `&self`: HTTP-транспорт обслуживает соединения пулом потоков
//! над ОДНИМ сервером. Пока обработка шла строго по одному, она же давала две
//! гарантии, которых теперь нет даром, и они сделаны явными:
//!
//! - **соединение SQLite не делится между потоками** — у проекта пул свободных
//!   соединений, вызов берёт своё и возвращает;
//! - **индекс не читается, пока пишется** — у проекта `RwLock`: вызовы
//!   инструментов держат его на чтение, досборка и удаление — на запись.

use crate::proto::{self, ErrorCode, Request};
use crate::tools::{self, Profile};
use rusqlite::Connection;
use serde_json::{json, Value};
use std::collections::HashMap;
use std::io::{BufRead, Write};
use std::path::PathBuf;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};
use std::sync::{Arc, Condvar, Mutex, MutexGuard, PoisonError, RwLock};
use std::time::Duration;

/// Сервер. Клонируется дёшево: клон делит состояние с оригиналом.
///
/// `Arc` внутри — не прихоть: фоновый поток автосинхронизации git
/// (`запустить_гит_синк`) должен видеть проекты, открываемые ПОСЛЕ его
/// старта, а до него `Server` уходил в потоки HTTP по значению.
#[derive(Clone)]
pub struct Server {
    в: Arc<Внутренность>,
}

struct Внутренность {
    /// Откуда брать индексы: один файл или каталог проектов (Р-004).
    источник: crate::registry::Источник,
    profile: Profile,
    /// Открытые проекты по ключу (путь индекса): открываются лениво, живут до
    /// конца сессии или до `delete_project`.
    ///
    /// Замок карты держится только на поиск и вставку — и на удаление
    /// проекта целиком (см. [`Server::удалить_проект`]). Сама работа с индексом
    /// идёт под замком ПРОЕКТА, иначе вызов по одной конфигурации ждал бы
    /// вызова по другой.
    проекты: Mutex<HashMap<String, Arc<Проект>>>,
    /// Включена ли автодосборка (флаг `--auto-update`).
    авто: bool,
    /// Интервал автосинхронизации git (флаг `--git-sync` / env); `None` — выключена.
    гит_интервал: Option<Duration>,
    /// Словарь векторов для автоматической полной пересборки (`--dict`).
    словарь: Option<PathBuf>,
}

/// Всё, что сервер держит про один открытый проект.
struct Проект {
    путь: PathBuf,
    /// Сторож свежести — свой на каждый проект (веха 7).
    ///
    /// Поднимается лениво: сервер обязан отвечать на `initialize` даже при
    /// недоступном индексе, а сторож — это уже работа с ним. Свой на проект
    /// потому, что у каждого индекса свой каталог исходников и своё время
    /// сборки; один сторож на всех отвечал бы про чужую конфигурацию.
    страж: crate::freshness_guard::FreshnessGuard,
    /// Автодосборка — своя на каждый проект, как и сторож.
    досборка: crate::autoupdate::Автодосборка,
    /// Git-синхронизация — своя на каждый проект: у каждого свой репозиторий
    /// и своё право быть пропущенным (грязная копия, не в git).
    гит: crate::gitsync::ГитСинк,
    /// Вызовы инструментов — на чтение; досборка и удаление — на запись.
    ///
    /// Ту же гарантию раньше давала последовательная обработка: пока индекс
    /// пишется, его никто не читает. Теперь она названа, а не подразумевается.
    замок: RwLock<()>,
    /// Свободные соединения на чтение.
    ///
    /// Пул, а не одно соединение: `Connection` нельзя делить между потоками.
    /// Пул, а не открытие на каждый вызов: открыть значит заплатить разбором
    /// схемы за каждый вопрос. Больше соединений, чем одновременных вызовов,
    /// здесь не бывает — то есть не больше числа потоков сервера.
    свободные: Mutex<Vec<Connection>>,
    /// Модулей в индексе — для интервала троттлинга досборки. Считается при
    /// открытии и после каждой досборки, а не на каждый вызов.
    модулей: AtomicU64,
    /// Когда последний раз пробовали догнать проект (unix, мс).
    ///
    /// Троттлинг. У образца досборку запускает фоновый наблюдатель по
    /// таймеру; у нас по вопросу агента — есть готовый повод проверить.
    /// Интервал образца применяется здесь как «не чаще, чем», иначе
    /// досборка шла бы на каждый вызов. (Фоновый поток в сервере теперь
    /// есть — но только для git-синхронизации; досборку он не дергает.)
    последняя_проверка: Mutex<Option<u64>>,
    /// Проект удалён `delete_project`. Вызов, успевший взять проект до
    /// удаления, получает отказ, а не открывает удалённый файл заново.
    удалён: AtomicBool,
}

/// Замок, переживающий панику в другом потоке.
///
/// Отравленный замок здесь ничего не значит: под ним лежат список соединений
/// и отметка времени, а не полузаписанный инвариант. Отказывать всем
/// следующим вызовам из-за одного упавшего было бы хуже самой паники.
fn взять_замок<T>(m: &Mutex<T>) -> MutexGuard<'_, T> {
    m.lock().unwrap_or_else(PoisonError::into_inner)
}

fn открыть_соединение(путь: &std::path::Path) -> Result<Connection, String> {
    crate::sql::open_readonly(путь).map_err(|e| {
        format!(
            "индекс {} недоступен: {e}. Соберите его:                      gyrfalcon build <путь> --out <файл>",
            путь.display()
        )
    })
}

fn посчитать_модули(c: &Connection) -> u64 {
    c.query_row("SELECT COUNT(*) FROM modules", [], |r| r.get::<_, i64>(0))
        .unwrap_or(0) as u64
}

impl Проект {
    /// Свободное соединение или новое, если все заняты.
    fn взять(&self) -> Result<Connection, String> {
        if let Some(c) = взять_замок(&self.свободные).pop() {
            return Ok(c);
        }
        открыть_соединение(&self.путь)
    }

    fn вернуть(&self, c: Connection) {
        взять_замок(&self.свободные).push(c);
    }
}

impl Server {
    pub fn new(источник: crate::registry::Источник, profile: Profile) -> Self {
        Self {
            в: Arc::new(Внутренность {
                источник,
                profile,
                проекты: Mutex::new(HashMap::new()),
                авто: false,
                гит_интервал: None,
                словарь: None,
            }),
        }
    }

    /// Настроить `Arc`-внутренность; зовётся только билдерами до первого клона.
    fn настроить(mut self, f: impl FnOnce(&mut Внутренность)) -> Self {
        let в = Arc::get_mut(&mut self.в).expect("настройка после клона сервера");
        f(в);
        self
    }

    /// Включить автодосборку индекса по изменившимся `.bsl`.
    pub fn с_автодосборкой(self, включена: bool) -> Self {
        self.настроить(|в| в.авто = включена)
    }

    /// Включить автосинхронизацию git с заданным интервалом.
    pub fn с_гит_синхронизацией(self, интервал: Option<Duration>) -> Self {
        self.настроить(|в| в.гит_интервал = интервал)
    }

    /// Словарь векторов для автоматических полных пересборок.
    pub fn со_словарём(self, словарь: Option<PathBuf>) -> Self {
        self.настроить(|в| в.словарь = словарь)
    }

    /// Проект, названный в аргументах вызова: открыть, если ещё не открыт.
    ///
    /// Открывается лениво и только на чтение. Лениво — чтобы сервер
    /// поднимался и отвечал `initialize` даже при недоступном индексе:
    /// клиент должен получить внятный отказ на вызове инструмента,
    /// а не молчание при старте.
    ///
    /// Открытие идёт под замком карты: два потока, впервые спросившие один
    /// проект, иначе подняли бы двух сторожей. Цена — открытие соединения и
    /// чтение метаданных индекса, сотые доли секунды, один раз на проект.
    fn открыть(&self, project: Option<&str>) -> Result<Arc<Проект>, String> {
        let путь = self.в.источник.путь(project).map_err(|e| e.to_string())?;
        let ключ = путь.to_string_lossy().to_string();
        let mut проекты = взять_замок(&self.в.проекты);
        if let Some(п) = проекты.get(&ключ) {
            return Ok(Arc::clone(п));
        }
        let c = открыть_соединение(&путь)?;
        let корень = gyrfalcon_index::build::info(&путь)
            .map(|i| std::path::PathBuf::from(i.source_path))
            .unwrap_or_default();
        let п = Arc::new(Проект {
            страж: crate::freshness_guard::FreshnessGuard::запустить(&путь),
            досборка: crate::autoupdate::Автодосборка::новая(
                &путь,
                &корень,
                self.в.авто,
            ),
            гит: crate::gitsync::ГитСинк::новый(&корень, self.в.гит_интервал),
            замок: RwLock::new(()),
            модулей: AtomicU64::new(посчитать_модули(&c)),
            свободные: Mutex::new(vec![c]),
            последняя_проверка: Mutex::new(None),
            удалён: AtomicBool::new(false),
            путь,
        });
        проекты.insert(ключ, Arc::clone(&п));
        Ok(п)
    }

    /// Обработать одно сообщение. `None` — отвечать не нужно (уведомление).
    pub fn handle(&self, line: &str) -> Option<Value> {
        let req: Request = match serde_json::from_str(line) {
            Ok(r) => r,
            Err(e) => {
                return Some(proto::err(
                    Value::Null,
                    ErrorCode::ParseError,
                    format!("не разобрал JSON: {e}"),
                ))
            }
        };

        // Уведомления ответа не требуют — на них молчим (это по протоколу,
        // а не потому, что нечего сказать).
        let id = req.id.clone()?;

        match req.method.as_str() {
            "initialize" => {
                // Версию диктует клиент, а не транспорт: по stdio приходят
                // 2024-11-05, по HTTP — 2025-03-26 и новее.
                let протокол = proto::согласовать_версию(
                    req.params.get("protocolVersion").and_then(Value::as_str),
                );
                Some(proto::ok(
                    id,
                    proto::initialize_result("gyrfalcon", env!("CARGO_PKG_VERSION"), протокол),
                ))
            }
            "ping" => Some(proto::ok(id, json!({}))),
            "tools/list" => {
                let список: Vec<Value> = tools::list(self.в.profile)
                    .iter()
                    .map(|t| {
                        json!({
                            "name": t.name,
                            "description": t.description,
                            "inputSchema": (t.schema)()
                        })
                    })
                    .collect();
                Some(proto::ok(id, json!({"tools": список})))
            }
            "tools/call" => {
                let имя = req
                    .params
                    .get("name")
                    .and_then(Value::as_str)
                    .unwrap_or_default()
                    .to_string();
                if имя.is_empty() {
                    return Some(proto::err(
                        id,
                        ErrorCode::InvalidParams,
                        "не указано имя инструмента",
                    ));
                }
                let args = req
                    .params
                    .get("arguments")
                    .cloned()
                    .unwrap_or_else(|| json!({}));
                let profile = self.в.profile;

                // `projects` отвечает про сам сервер, а не про конкретный
                // индекс: ему проект не нужен и открывать ничего не надо.
                if имя == "delete_project" {
                    let итог = self.удалить_проект(&args);
                    return Some(match итог {
                        Ok(v) => proto::ok(
                            id,
                            proto::tool_result(
                                serde_json::to_string(&v).unwrap_or_else(|e| e.to_string()),
                                false,
                            ),
                        ),
                        Err(e) => proto::ok(id, proto::tool_result(e, true)),
                    });
                }

                if имя == "list_projects" {
                    return Some(proto::ok(
                        id,
                        proto::tool_result(
                            serde_json::to_string(&self.перечислить())
                                .unwrap_or_else(|e| e.to_string()),
                            false,
                        ),
                    ));
                }

                let итог = self.выполнить(profile, &имя, &args);
                // Ошибка инструмента — это успешный ответ с isError, а не
                // ошибка протокола: клиент должен отличать «не вышло» от
                // «сервер сломан».
                Some(match итог {
                    Ok(v) => proto::ok(
                        id,
                        proto::tool_result(
                            serde_json::to_string(&v).unwrap_or_else(|e| e.to_string()),
                            false,
                        ),
                    ),
                    Err(e) => proto::ok(id, proto::tool_result(e, true)),
                })
            }
            other => Some(proto::err(
                id,
                ErrorCode::MethodNotFound,
                format!("метод не поддерживается: {other}"),
            )),
        }
    }

    /// Догнать индекс проекта по накопившимся правкам `.bsl`.
    ///
    /// Вызывается перед выполнением инструмента и почти всегда не делает
    /// ничего: очередь пуста либо интервал ещё не вышел.
    ///
    /// # Почему соединения закрываются
    ///
    /// Инструменты держат соединения ТОЛЬКО НА ЧТЕНИЕ, а инкремент пишет.
    /// Держать рядом второе, пишущее, значило бы получить `database is
    /// locked` в самый неудачный момент — поэтому свободные читающие
    /// закрываются на время записи, а занятых в этот момент нет: запись идёт
    /// под замком проекта на запись. Цена — разбор схемы один раз на
    /// досборку, то есть примерно никогда.
    ///
    /// # Гонка, которая допущена сознательно
    ///
    /// Вызов, пришедший в тот же интервал троттлинга, что и досборка, но
    /// успевший взять замок на чтение раньше неё, ответит по индексу до
    /// досборки. При обработке по одному он отвечал бы после. Разница — один
    /// ответ по индексу, отстающему на правки последних секунд; ради неё
    /// держать все вызовы проекта до конца проверки троттлинга не стоит.
    fn догнать(&self, п: &Проект) {
        if !self.в.авто || !п.досборка.включена() {
            return;
        }
        let очередь = п.страж.очередь();
        if очередь.is_empty() {
            return;
        }

        // Троттлинг по формуле образца: интервал растёт с размером корпуса.
        let сейчас = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_millis() as u64)
            .unwrap_or(0);
        let интервал = crate::autoupdate::интервал_мс(п.модулей.load(Ordering::Acquire));
        {
            let mut прошлая = взять_замок(&п.последняя_проверка);
            if let Some(прошлая) = *прошлая {
                if сейчас.saturating_sub(прошлая) < интервал {
                    return;
                }
            }
            *прошлая = Some(сейчас);
        }

        let _ = self.применить_инкремент(п, &очередь);
    }

    /// Записать инкремент под замком проекта: закрыть свободные соединения,
    /// применить, сбросить кэш семантики, признать догнанным.
    ///
    /// Общий путь досборки по событиям (`догнать`) и по pull
    /// (`синхронизировать`): протокол один, и растроживать его на две
    /// копии значило бы разойтись в самый нужный момент — одна правила бы
    /// соединения, другая нет.
    ///
    /// Возвращает `Ok` только когда инкремент прошёл.
    fn применить_инкремент(
        &self,
        п: &Проект,
        файлы: &[PathBuf],
    ) -> Result<(), crate::autoupdate::Отказ> {
        // Закрыть читающие соединения на время записи (см. `догнать`).
        let _запись = п.замок.write().unwrap_or_else(PoisonError::into_inner);
        if п.удалён.load(Ordering::Acquire) {
            return Err(crate::autoupdate::Отказ::Сбой("проект удалён".into()));
        }
        взять_замок(&п.свободные).clear();
        let итог = п.досборка.догнать(файлы);
        // Векторы в памяти после записи в индекс — уже не правда. Отпечаток
        // файла это тоже заметит, но разрешение mtime не повод рисковать.
        gyrfalcon_index::semantic::cache::forget(&п.путь);
        if let Ok(c) = открыть_соединение(&п.путь) {
            п.модулей.store(посчитать_модули(&c), Ordering::Release);
            п.вернуть(c);
        }

        // Базовую линию сдвигаем ТОЛЬКО при успехе — правило образца (#937).
        // Отказ по метаданным и сбой оставляют очередь нетронутой: отметка
        // сторожа продолжает говорить, что индекс отстал, и это правда.
        if итог.is_ok() {
            п.страж.признать_догнанным(файлы);
        }
        итог.map(|_| ())
    }

    /// Полная пересборка индекса проекта с подменой файла под замком.
    ///
    /// Зовётся git-синхронизацией, когда pull привёз метаданные: инкремент
    /// их не берёт, а оставить индекс расходящимся молча — хуже пересборки.
    ///
    /// # Почему сборка во временный файл, а не поверх живого
    ///
    /// `build` стирает и пишет выход заново; живой файл в это время кормит
    /// ответы. Временный файл засеивается копией старого индекса — так в нём
    /// выживает снимок Help-корпуса (`build` читает его из выхода), — затем
    /// атомарно переименовывается поверх живого под тем же замком проекта.
    ///
    /// # Почему замок держится всю сборку
    ///
    /// Сборка идёт минуты, и всё это время вызовы проекта ждут. Альтернатива —
    /// короткий замок только на подмену — рискует потерять инкремент,
    /// вписанный между сборкой и подменой вместе со старым файлом. Выбрана
    /// корректность против задержки, и только в пределах одного проекта.
    fn полная_пересборка(&self, п: &Проект) -> Result<(), String> {
        let stem = п
            .путь
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("index");
        let темп = п
            .путь
            .with_file_name(format!(".{stem}.sync-{}.db", std::process::id()));
        std::fs::copy(&п.путь, &темп)
            .map_err(|e| format!("не скопировать индекс для пересборки: {e}"))?;

        let итог = (|| -> Result<(), String> {
            let _запись = п.замок.write().unwrap_or_else(PoisonError::into_inner);
            if п.удалён.load(Ordering::Acquire) {
                return Err("проект удалён".into());
            }
            gyrfalcon_index::build(п.гит.корень(), &темп, self.в.словарь.as_deref())
                .map_err(|e| e.to_string())?;
            // Свободные соединения закрываются: держат старый файл занятым,
            // и rename поверх него отказал бы. Занятых нет — замок на запись.
            взять_замок(&п.свободные).clear();
            std::fs::rename(&темп, &п.путь)
                .map_err(|e| format!("не подменить индекс: {e}"))?;
            gyrfalcon_index::semantic::cache::forget(&п.путь);
            // Сторож должен узнать о НОВОЙ базе: старые счётчики и очередь
            // говорили про индекс, которого больше нет.
            п.страж.пересобран(&п.путь);
            if let Ok(c) = открыть_соединение(&п.путь) {
                п.модулей.store(посчитать_модули(&c), Ordering::Release);
                п.вернуть(c);
            }
            Ok(())
        })();
        if итог.is_err() {
            let _ = std::fs::remove_file(&темп);
        }
        итог
    }

    /// Запустить фоновую автосинхронизацию git (см. `gitsync`).
    ///
    /// Поток живёт до конца процесса: stdio-сервер кончается по EOF stdin,
    /// HTTP — закрытием listener'а. Возврат — ручка для тестов: `остановить`
    /// присоединяет нить за секунду вместо интервалов.
    pub fn запустить_гит_синк(&self) -> Option<ГитСинкПоток> {
        let интервал = self.в.гит_интервал?;
        let сервер = self.clone();
        let стоп = Arc::new((Mutex::new(false), Condvar::new()));
        let для_нити = Arc::clone(&стоп);
        let нить = std::thread::Builder::new()
            .name("git-sync".into())
            .spawn(move || {
                loop {
                    let (замок, вар) = &*для_нити;
                    let (остановлен, _) = {
                        let охрана = замок.lock().unwrap();
                        if *охрана {
                            break;
                        }
                        вар.wait_timeout(охрана, интервал).unwrap()
                    };
                    if *остановлен {
                        break;
                    }
                    сервер.такт_гит();
                }
            })
            .expect("нить git-sync");
        Some(ГитСинкПоток {
            нить: Some(нить),
            стоп,
        })
    }

    /// Один такт по всем ОБЪЯВЛЕННЫМ проектам.
    ///
    /// Проекты открываются здесь ДО синхронизации, а не ждут первого вопроса
    /// агента: смысл `--git-sync` в том, что выгрузка подтянется и индекс
    /// догонит ЗАРАНЕЕ — «синхронизация после того, как спросили» не стоила
    /// бы своего флага. Отсюда отступление от ленивого открытия: такт сам
    /// зовёт `открыть`, и сторож со подпиской поднимаются на один раньше.
    ///
    /// Битый индекс не открывается — и это не останавливает остальных:
    /// отказ уже виден в `list_projects` нулями в счётчиках.
    fn такт_гит(&self) {
        let имена: Vec<Option<String>> = match &self.в.источник {
            crate::registry::Источник::Один { .. } => vec![None],
            crate::registry::Источник::Каталог(_) => self
                .в
                .источник
                .перечислить()
                .into_iter()
                .map(|п| Some(п.имя))
                .collect(),
        };
        for имя in имена {
            let Ok(п) = self.открыть(имя.as_deref()) else {
                continue;
            };
            self.синхронизировать(&п);
        }
    }

    /// Синхронизировать один проект: pull, затем инкремент или пересборка.
    ///
    /// События подписки от тех же файлов встанут в очередь сторожа — и при
    /// включённой автодосборке `догнать` перепроверит их второй сеткой.
    /// Повторный инкремент по тем же файлам идемпотентен: берёт их же mtime.
    fn синхронизировать(&self, п: &Проект) {
        if !п.гит.включена() || !п.гит.занять() {
            return;
        }
        let итог = self.один_такт(п);
        п.гит.записать_итог(итог);
        п.гит.освободить();
    }

    fn один_такт(&self, п: &Проект) -> String {
        let файлы = match п.гит.тянуть() {
            Ok(f) => f,
            // Причину (с префиксом ПРОПУЩЕНО/ОШИБКА) `тянуть` уже записал
            // в состояние сам — здесь она лишь возвращается вызывающему.
            Err(причина) => return причина,
        };
        if файлы.is_empty() {
            return "pull без изменений".into();
        }
        match crate::autoupdate::Автодосборка::разобрать(&файлы) {
            Ok(bsl) => match self.применить_инкремент(п, &bsl) {
                Ok(()) => {
                    self.снять_опоздавшие_события(п, &bsl);
                    format!("pull: {} .bsl, инкремент применён", bsl.len())
                }
                Err(e) => format!("ОШИБКА инкремента после pull: {e:?}"),
            },
            Err(crate::autoupdate::Отказ::ЕстьМетаданные { xml, bsl }) => {
                match self.полная_пересборка(п) {
                    Ok(()) => format!(
                        "pull: {xml} .xml, {bsl} .bsl — полная пересборка{}",
                        if self.в.словарь.is_none() {
                            " (без словаря: включите --dict, чтобы семантика не деградировала)"
                        } else {
                            ""
                        }
                    ),
                    Err(e) => format!("ОШИБКА пересборки после pull: {e}"),
                }
            }
            // Изменились файлы, которых индекс не касается (не .bsl/.xml).
            Err(_) => "pull без изменений по коду".into(),
        }
    }

    /// Вторая чистка очереди сторожа теми же путями, с задержкой.
    ///
    /// Подписка на события файловой системы отдаёт события pull'а с задержкой
    /// (FSEvents на macOS — до секунды): часть приезжает ПОСЛЕ того, как
    /// инкремент признал файлы догнанными, и отметка «индекс отстал» стоит
    /// на свежем индексе. С автодосборкой её снял бы следующий вызов, а без
    /// неё — некому; здесь поток фоновый, и подождать полсекунды бесплатно.
    /// Убираются только пути ПРИЕХАВШИЕ: локальная правка, случившаяся в
    /// окно ожидания, в очередь встала и в ней останется.
    fn снять_опоздавшие_события(&self, п: &Проект, файлы: &[PathBuf]) {
        std::thread::sleep(Duration::from_millis(700));
        п.страж.признать_догнанным(файлы);
    }

    /// Вызвать инструмент по одному проекту: замок на чтение, своё соединение.
    fn вызвать(
        &self,
        п: &Проект,
        profile: Profile,
        имя: &str,
        args: &Value,
    ) -> Result<Value, String> {
        let _чтение = п.замок.read().unwrap_or_else(PoisonError::into_inner);
        if п.удалён.load(Ordering::Acquire) {
            return Err(format!(
                "индекс {} удалён инструментом delete_project, пока вызов ждал очереди",
                п.путь.display()
            ));
        }
        let c = п.взять()?;
        let r = tools::call(&c, profile, имя, args);
        п.вернуть(c);
        r
    }

    /// Выполнить инструмент по одному или нескольким проектам.
    ///
    /// `project` принимает три формы (устройство взято у образца,
    /// `target_projects`): строку, массив строк и `"*"` — все проекты.
    ///
    /// # Почему ответ по нескольким выглядит иначе
    ///
    /// Он не склеивается в одну таблицу. Строки разных конфигураций
    /// одинаковы на вид и означают разное: `Контрагенты` из ЕРП.УХ и
    /// `Контрагенты` из БП — разные объекты разных баз. Склеенная таблица
    /// это скрывает, и вывод о «дубле» или «единственном совпадении»
    /// делается по перемешанным данным. Поэтому ответ — карта
    /// «проект → его ответ», и принадлежность каждой строки видна.
    fn выполнить(
        &self,
        profile: Profile,
        имя: &str,
        args: &Value,
    ) -> Result<Value, String> {
        let mut цели = разобрать_цели(args);

        // Звёздочка разворачивается ДО выбора ветки. Иначе `project: "*"`
        // — одна строка, то есть «одна цель», — уходила бы в поиск проекта
        // с именем `*`, которого нет. Поймано живой пробой: отказ
        // «проект '*' не найден» при трёх доступных.
        if цели.iter().any(|ц| ц == "*") {
            цели = self.в.источник.имена_всех();
        }

        // Одна цель (или ни одной) — прежний путь, ответ без обёртки.
        if цели.len() <= 1 {
            let один = цели.first().map(String::as_str);
            let п = self.открыть(один)?;
            // Догнать индекс ДО ответа, а не после: смысл автодосборки в том,
            // чтобы агент получил ответ по свежему индексу, а не узнал задним
            // числом, что отвечали ему по вчерашнему.
            self.догнать(&п);
            // Отметка свежести приписывается к УСПЕШНОМУ ответу (веха 7)
            // и берётся у сторожа ЭТОГО проекта. К отказу — нет: у отказа
            // своя причина, и две беды в одном тексте читаются как одна.
            return self
                .вызвать(&п, profile, имя, args)
                .map(|v| п.страж.пометить(v));
        }

        let список = self.в.источник.пути(&цели).map_err(|e| e.to_string())?;
        let mut ответы = serde_json::Map::new();
        let mut удачных = 0usize;
        for (проект, _) in &список {
            // Отказ по ОДНОМУ проекту не отменяет остальные: индекс мог быть
            // испорчен, и «всё упало» скрыло бы работающие ответы. Но и молча
            // пропустить нельзя — он попадает в ответ как ошибка этой строки.
            let значение = match self.открыть(Some(проект)) {
                Ok(п) => match self.вызвать(&п, profile, имя, args) {
                    Ok(v) => {
                        удачных += 1;
                        п.страж.пометить(v)
                    }
                    Err(e) => json!({"error": e}),
                },
                Err(e) => json!({"error": e}),
            };
            ответы.insert(проект.clone(), значение);
        }
        Ok(json!({
            "by_project": Value::Object(ответы),
            "projects_queried": список.len(),
            "projects_answered": удачных,
            "note": "Ответы разделены по конфигурациям намеренно: одноимённые                      объекты разных баз — разные объекты, и склеенная таблица                      скрыла бы, чей это результат"
        }))
    }

    /// Удалить проект: закрыть его, снять сторожа, убрать файл.
    ///
    /// # Почему это инструмент, а не `rm`
    ///
    /// Первая редакция обходилась без него с доводом «проект — это файл,
    /// удаление — это `rm`». Довод оказался неверным, и проверка заняла
    /// одну пробу: пока сервер работает, `rm` на Windows **не проходит
    /// вовсе** — `WinError 32`, файл занят процессом. Чтобы удалить
    /// конфигурацию, пришлось бы гасить сервер, то есть ронять работу
    /// всех агентов ради одной базы.
    ///
    /// Порядок здесь тот же, что у образца (так же устроено у индексаторов общего назначения), и
    /// каждый шаг обязателен:
    ///
    /// 1. **закрыть соединения** — иначе файл занят и удаление откажет;
    /// 2. **снять сторожа** — наблюдатель за исчезнувшим каталогом это
    ///    поток, следящий за пустотой, и живёт он до конца сессии;
    /// 3. **удалить файл** вместе со спутниками SQLite;
    /// 4. **назвать исход словом**, а не «готово»: удалён, не найден,
    ///    не удалось — с причиной.
    ///
    /// # Почему замок карты держится до конца
    ///
    /// Иначе вызов, пришедший между «проект убран из карты» и «файл удалён»,
    /// открыл бы проект заново — и файл снова оказался бы занят. Остальные
    /// проекты на это время не открываются впервые; уже открытые работают:
    /// вызовы инструментов замка карты не берут.
    ///
    /// Чего здесь НЕТ по сравнению с образцом: блокировки конвейера
    /// индексации. У них сборка идёт в том же процессе и её надо дождаться;
    /// у нас `build` — отдельная команда, и параллельная сборка пишет
    /// в свой файл.
    fn удалить_проект(&self, args: &Value) -> Result<Value, String> {
        let имя = args
            .get("project")
            .and_then(Value::as_str)
            .ok_or("нужен параметр project: удалять без имени нечего")?;

        let путь = self.в.источник.путь(Some(имя)).map_err(|e| e.to_string())?;
        let ключ = путь.to_string_lossy().to_string();

        let mut проекты = взять_замок(&self.в.проекты);
        // 1-2. Закрыть и снять сторожа. Замок проекта на запись дожидается
        // идущих вызовов; после него занятых соединений нет, а свободные
        // закрываются очисткой пула — у `Connection` освобождение в `Drop`.
        // Сторож уходит вместе с последней ссылкой на проект.
        let было_открыто = match проекты.remove(&ключ) {
            Some(п) => {
                let _запись = п.замок.write().unwrap_or_else(PoisonError::into_inner);
                п.удалён.store(true, Ordering::Release);
                взять_замок(&п.свободные).clear();
                true
            }
            None => false,
        };

        // 3. Удалить файл и спутники. `-wal`/`-shm` у нас не появляются
        // (индекс открывается только на чтение), но сборка идёт на запись,
        // и оборванная сборка их оставляет. Чистим — иначе они переживут
        // свой индекс и будут занимать место без всякой пользы.
        // Ветка недостижима на обычном пути: реестр отсекает несуществующий
        // проект раньше, отказом «не найден» с перечнем доступных (проверено
        // живьём — повторное удаление даёт именно его). Оставлена для гонки:
        // файл могли удалить между разрешением имени и этой строкой.
        if !путь.is_file() {
            return Ok(json!({
                "project": имя,
                "status": "not_found",
                "note": "файла индекса нет — удалять нечего"
            }));
        }
        if let Err(e) = std::fs::remove_file(&путь) {
            return Ok(json!({
                "project": имя,
                "status": "delete_failed",
                "error": e.to_string(),
                "note": "индекс закрыт сервером, но файл не удалён.                          Обычная причина — файл открыт другим процессом                          (вторым сервером, сборкой, просмотрщиком SQLite)"
            }));
        }
        let mut спутники = 0;
        for суффикс in ["-wal", "-shm"] {
            let спутник = PathBuf::from(format!("{}{суффикс}", путь.display()));
            if спутник.is_file() && std::fs::remove_file(&спутник).is_ok() {
                спутники += 1;
            }
        }
        drop(проекты);

        Ok(json!({
            "project": имя,
            "status": "deleted",
            "path": путь.display().to_string(),
            "was_open": было_открыто,
            "companions_removed": спутники,
            "note": "удалён ИНДЕКС, а не исходники конфигурации.                      Собрать заново: gyrfalcon build <путь> --out <файл>"
        }))
    }

    /// Ответ инструмента `projects`.
    ///
    /// Отдаёт и состояние сторожа свежести по каждому открытому проекту.
    /// Причина в вопросе, на который иначе нечем ответить: «свежий индекс
    /// молчит» — значит молчание надо уметь ПРОВЕРИТЬ. Без этого оно
    /// означает и «всё хорошо», и «сторож не встал, и ты не узнаешь».
    fn перечислить(&self) -> Value {
        // Снимок карты: перечень читает файлы индексов, и держать замок
        // карты всё это время значило бы не давать открывать проекты.
        let открытые = взять_замок(&self.в.проекты).clone();
        let строки: Vec<Value> = self
            .в.источник
            .перечислить()
            .into_iter()
            .map(|p| {
                let ключ = p.индекс.to_string_lossy().to_string();
                let проект = открытые.get(&ключ);
                // Проект, которого ещё не спрашивали в этой сессии, сторожа
                // не имеет — и это называется прямо, а не выдаётся молчанием
                // за «всё хорошо».
                let mut свежесть = match проект {
                    Some(п) => п.страж.состояние(),
                    None => json!({"checked": "не открывался в этой сессии"}),
                };
                // Автодосборка — часть ответа на «откуда я знаю, что всё
                // нормально»: выключенная она говорит об этом прямо, иначе
                // «ничего не досбиралось» читалось бы как «нечего было».
                //
                // Проект, не открытый в этой сессии, своей `Автодосборки`
                // ещё не имеет — `list_projects` проектов не открывает.
                // Но флаг сервера известен всегда, и отвечать `null` на
                // вопрос «включена ли она» нельзя: спрашивают именно затем,
                // чтобы узнать состояние, а `null` читается как «неизвестно»
                // там, где известно. Поймано живой пробой 31.08.2026 сразу
                // после включения флага в конфигурации.
                if let Some(o) = свежесть.as_object_mut() {
                    match проект {
                        Some(п) => {
                            if let Some(состояние) = п.досборка.состояние().as_object()
                            {
                                for (k, v) in состояние {
                                    o.insert(k.clone(), v.clone());
                                }
                            }
                            // Git-синхронизация — та же честность: «не тянется»
                            // обязано отличаться от «тянуть нечего».
                            if let Some(состояние) = п.гит.состояние().as_object() {
                                for (k, v) in состояние {
                                    o.insert(k.clone(), v.clone());
                                }
                            }
                        }
                        None => {
                            o.insert(
                                "auto_update".into(),
                                json!(if self.в.авто {
                                    "включена"
                                } else {
                                    "выключена"
                                }),
                            );
                            o.insert(
                                "git_sync".into(),
                                json!(match self.в.гит_интервал {
                                    Some(d) => format!(
                                        "включена (каждые {})",
                                        crate::gitsync::описать_интервал(d)
                                    ),
                                    None => "выключена".to_string(),
                                }),
                            );
                        }
                    }
                }
                json!([p.имя, p.исходники, p.модулей, p.методов, p.собран, свежесть])
            })
            .collect();
        let mut ответ = json!({
            "columns": ["project", "source_path", "modules", "methods", "built_at", "freshness"],
            "rows": строки,
            "count": строки.len(),
            "note": "built_at — секунды эпохи. Нули в счётчиках значат, что файл                      индекса есть, но не читается — это видно намеренно, чтобы                      испорченный индекс не пропадал из списка молча.                      freshness отвечает на вопрос «а откуда я знаю, что всё                      нормально»: свежий индекс в ответах инструментов МОЛЧИТ,                      и проверить это молчание можно только здесь"
        });
        // Скилл и роли, отставшие от сервера: агент с правилами прошлой
        // версии не знает о новых инструментах, и сказать ему об этом
        // может только ответ — `list_projects` зовут первым.
        let отставшие = crate::install::отставшие_установки();
        if !отставшие.is_empty() {
            ответ["installed_files_outdated"] = json!(отставшие);
        }
        ответ
    }

    pub fn описание_источника(&self) -> String {
        match &self.в.источник {
            crate::registry::Источник::Один { путь, .. } => {
                путь.display().to_string()
            }
            crate::registry::Источник::Каталог(d) => {
                format!(
                    "каталог {} ({} проектов)",
                    d.display(),
                    self.в.источник.перечислить().len()
                )
            }
        }
    }

    /// Читать stdin до конца, отвечая в stdout.
    pub fn run(&self) -> std::io::Result<()> {
        let stdin = std::io::stdin();
        let mut stdout = std::io::stdout();
        eprintln!(
            "gyrfalcon {} — MCP на stdio, индекс {}, профиль {:?}",
            env!("CARGO_PKG_VERSION"),
            self.описание_источника(),
            self.в.profile
        );
        for line in stdin.lock().lines() {
            let line = line?;
            if line.trim().is_empty() {
                continue;
            }
            if let Some(ответ) = self.handle(&line) {
                serde_json::to_writer(&mut stdout, &ответ)?;
                stdout.write_all(b"\n")?;
                stdout.flush()?;
            }
        }
        Ok(())
    }
}

/// Ручка фоновой нити git-синхронизации.
///
/// В проду роняется на полпути (`let _поток = …`): нить продолжает жить
/// до конца процесса. В тесте — `остановить()`: просит нить кончиться
/// и присоединяет её, не дожидаясь интервала.
pub struct ГитСинкПоток {
    нить: Option<std::thread::JoinHandle<()>>,
    стоп: Arc<(Mutex<bool>, Condvar)>,
}

impl ГитСинкПоток {
    pub fn остановить(mut self) {
        *self.стоп.0.lock().unwrap() = true;
        self.стоп.1.notify_all();
        if let Some(нить) = self.нить.take() {
            let _ = нить.join();
        }
    }
}

/// Извлечь список проектов из аргументов вызова.
///
/// Пусто — проект не назван (реестр решит, отказ это или единственный
/// индекс). Одно имя — строка. Несколько — массив. `"*"` передаётся дальше
/// как есть: разворачивает его реестр, который один знает состав.
fn разобрать_цели(args: &Value) -> Vec<String> {
    match args.get("project") {
        Some(Value::String(s)) => vec![s.clone()],
        Some(Value::Array(a)) => a
            .iter()
            .filter_map(Value::as_str)
            .map(str::to_string)
            .collect(),
        _ => Vec::new(),
    }
}

