    /// Гит-проект целиком: клон с выгрузкой 1С, индекс из неё, сервер
    /// с включённой синхронизацией. Origin и второй клон — чтобы правке
    /// было откуда приехать (как в тестах `gitsync`).
    struct ГитСервер {
        _база: PathBuf,
        клон: PathBuf,
        второй: PathBuf,
        индекс: PathBuf,
        сервер: Server,
    }

    impl ГитСервер {
        fn новый(метка: &str) -> Self {
            let база = std::env::temp_dir().join(format!(
                "gyrfalcon-srvgit-{метка}-{}",
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&база);
            std::fs::create_dir_all(&база).unwrap();
            let git = |корень: &PathBuf, a: &[&str]| {
                let ok = std::process::Command::new("git")
                    .args([
                        "-c",
                        "user.name=t",
                        "-c",
                        "user.email=t@t",
                        "-c",
                        "core.autocrlf=false",
                        "-c",
                        "commit.gpgsign=false",
                    ])
                    .arg("-C")
                    .arg(корень)
                    .args(a)
                    .status()
                    .unwrap()
                    .success();
                assert!(ok, "git {a:?}");
            };
            git(&база, &["init", "-q", "--bare", "origin.git"]);
            git(&база, &["init", "-q", "клон"]);
            let клон = база.join("клон");
            let w = |p: &str, t: &str| {
                let f = клон.join(p);
                std::fs::create_dir_all(f.parent().unwrap()).unwrap();
                std::fs::write(f, t).unwrap();
            };
            w(
                "src/Configuration.xml",
                "<MetaDataObject><Configuration><Properties><Name>Т</Name>\
                 </Properties></Configuration></MetaDataObject>",
            );
            w(
                "src/CommonModules/ОбщегоНазначения/Ext/Module.bsl",
                "Функция ЗначениеРеквизита(С) Экспорт\n\tВозврат С;\nКонецФункции\n",
            );
            git(&клон, &["add", "-A"]);
            git(&клон, &["commit", "-q", "-m", "init"]);
            git(&клон, &["remote", "add", "origin", "../origin.git"]);
            git(&клон, &["push", "-q", "-u", "origin", "HEAD"]);
            git(&база, &["clone", "-q", "origin.git", "второй"]);
            let индекс = база.join("index.db");
            gyrfalcon_index::build(&клон.join("src"), &индекс, None).unwrap();
            let сервер = Server::new(
                crate::registry::Источник::Один {
                    имя: метка.into(),
                    путь: индекс.clone(),
                },
                Profile::All,
            )
            .с_гит_синхронизацией(Some(Duration::from_secs(1)));
            Self {
                _база: база.clone(),
                клон,
                второй: база.join("второй"),
                индекс,
                сервер,
            }
        }

        /// Новый коммит в origin — через второй клон.
        fn перевалка(&self, путь: &str, текст: &str) {
            let f = self.второй.join(путь);
            std::fs::create_dir_all(f.parent().unwrap()).unwrap();
            std::fs::write(f, текст).unwrap();
            let ok = std::process::Command::new("git")
                .args([
                    "-c",
                    "user.name=t",
                    "-c",
                    "user.email=t@t",
                    "-c",
                    "commit.gpgsign=false",
                ])
                .arg("-C")
                .arg(&self.второй)
                .args(["add", "-A"])
                .status()
                .unwrap()
                .success();
            assert!(ok);
            let ok = std::process::Command::new("git")
                .args(["-c", "user.name=t", "-c", "user.email=t@t"])
                .arg("-C")
                .arg(&self.второй)
                .args(["commit", "-q", "-m", "правка"])
                .status()
                .unwrap()
                .success();
            assert!(ok);
            let ok = std::process::Command::new("git")
                .arg("-C")
                .arg(&self.второй)
                .args(["push", "-q"])
                .status()
                .unwrap()
                .success();
            assert!(ok);
        }

        fn итог(&self, п: &Проект) -> String {
            п.гит.состояние()["last_result"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        }
    }

