    #[test]
    fn xml_после_pull_пересобирает_индекс_и_не_оставляет_временного() {
        let гс = ГитСервер::новый("пересборка");
        let п = гс.сервер.открыть(None).unwrap();
        let было = gyrfalcon_index::build::info(&гс.индекс).unwrap().built_at;
        // built_at — секунды эпохи: без паузы новая сборка не отличима.
        std::thread::sleep(Duration::from_millis(1100));
        гс.перевалка("src/Catalogs/Товары.xml", "<MetaDataObject/>\n");
        гс.сервер.синхронизировать(&п);
        let итог = гс.итог(&п);
        assert!(итог.contains("пересборка"), "итог: {итог}");
        let стало = gyrfalcon_index::build::info(&гс.индекс).unwrap().built_at;
        assert!(стало > было, "индекс пересобран: {было} → {стало}");
        let каталог = гс.индекс.parent().unwrap();
        let мусор = std::fs::read_dir(каталог)
            .unwrap()
            .filter_map(|e| e.ok())
            .any(|e| e.file_name().to_string_lossy().contains(".sync-"));
        assert!(!мусор, "временный файл пересборки убран");
        // Сервер отвечает по НОВОМУ индексу: соединение переоткрыто.
        let r = гс
            .сервер
            .handle(&вызов_sql(1, "SELECT COUNT(*) FROM modules"))
            .unwrap();
        assert_ne!(r["result"]["isError"], true, "{}", текст(&r));
    }

    #[test]
    fn грязная_выгрузка_пропускается_а_индекс_живёт() {
        let гс = ГитСервер::новый("пропуск");
        let п = гс.сервер.открыть(None).unwrap();
        гс.перевалка(
            "src/CommonModules/ОбщегоНазначения/Ext/Module.bsl",
            "новое из origin\n",
        );
        // Локальная правка в выгрузке: человек важнее синхронизации.
        let ф = гс.клон.join("src/CommonModules/ОбщегоНазначения/Ext/Module.bsl");
        let mut т = std::fs::read_to_string(&ф).unwrap();
        т.push_str("// локальная правка\n");
        std::fs::write(&ф, т).unwrap();
        гс.сервер.синхронизировать(&п);
        let итог = гс.итог(&п);
        assert!(итог.contains("грязная"), "итог: {итог}");
        // HEAD не двинулся и индекс отвечает.
        let r = гс
            .сервер
            .handle(&вызов_sql(1, "SELECT COUNT(*) FROM modules"))
            .unwrap();
        assert_ne!(r["result"]["isError"], true, "{}", текст(&r));
    }

    #[test]
    fn нить_синхронизации_делает_такты_и_останавливается_быстро() {
        let гс = ГитСервер::новый("нить");
        let п = гс.сервер.открыть(None).unwrap();
        let ручка = гс.сервер.запустить_гит_синк().unwrap();
        // Ждём первого такта (интервал 1 с) — не строго, а с запасом.
        let край = std::time::Instant::now() + Duration::from_secs(5);
        while п.гит.состояние()["last_pull"].is_null() {
            if std::time::Instant::now() > край {
                panic!("первый такт не прошёл за 5 с");
            }
            std::thread::sleep(Duration::from_millis(50));
        }
        let начал = std::time::Instant::now();
        ручка.остановить();
        assert!(
            начал.elapsed() < Duration::from_secs(2),
            "остановить обязан присоединять нить быстро, а не ждать интервала"
        );
    }
